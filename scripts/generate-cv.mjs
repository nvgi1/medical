/**
 * Selectable-text bilingual CV generation from the same editable source data.
 * Contract: two A4 single-column PDFs, Arabic RTL and English LTR; all requested
 * CV sections; no invented credentials; explicit template status. No advice,
 * charts, images or proficiency scores. Regenerate after updating content.ts.
 */
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import ts from "typescript";
import { chromium } from "playwright";
import { PDFDocument } from "pdf-lib";

const root = resolve(import.meta.dirname, "..");
const source = await readFile(resolve(root, "src/data/content.ts"), "utf8");
const js = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
  },
}).outputText;
const { profile, resumeSections, resumeContent } = await import(
  `data:text/javascript;base64,${Buffer.from(js).toString("base64")}`
);
const esc = (s) =>
  String(s).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
const font = async (name) =>
  `data:font/ttf;base64,${(await readFile(resolve(root, "public/fonts", name))).toString("base64")}`;
const arRegular = await font("IBM-Plex-Arabic-Regular.ttf"),
  arSemi = await font("IBM-Plex-Arabic-Semibold.ttf");
const enRegular = await font("Manrope-Regular.ttf"),
  enSemi = await font("Manrope-Semibold.ttf");
const browser = await chromium.launch({
  headless: true,
  channel: "chromium",
  ...(existsSync("/opt/pplx-chromium/chrome")
    ? { executablePath: "/opt/pplx-chromium/chrome" }
    : {}),
});
await mkdir(resolve(root, "public/cv"), { recursive: true });
await mkdir(resolve(root, "qa"), { recursive: true });
const embeddedPdfs = {};
try {
  for (const lang of ["ar", "en"]) {
    const t = (value) => value[lang],
      isAr = lang === "ar";
    const content = resumeContent.map(t);
    const html = `<!doctype html><html lang="${lang}" dir="${isAr ? "rtl" : "ltr"}"><head><meta charset="utf-8"/><style>
  @font-face{font-family:CVArabic;src:url("${arRegular}");font-weight:400}@font-face{font-family:CVArabic;src:url("${arSemi}");font-weight:600}
  @font-face{font-family:CVLatin;src:url("${enRegular}");font-weight:400}@font-face{font-family:CVLatin;src:url("${enSemi}");font-weight:600}
  @page{size:A4;margin:17mm 19mm}*{box-sizing:border-box}body{margin:0;color:#17282e;font:10pt/1.75 ${isAr ? "CVArabic" : "CVLatin"},sans-serif}
  .template{font-size:8pt;color:#61777b;border-bottom:1px solid #ced9d9;padding-bottom:7mm}header{padding:6mm 0 4mm;border-bottom:1px solid #54777a}
  h1{font-size:24pt;font-weight:600;line-height:1.4;margin:0 0 2mm}header p{margin:0;font-size:10pt}header small{font-size:8pt;color:#5b7379}
  section{margin-top:4mm;break-inside:avoid}h2{font-size:11pt;font-weight:600;margin:0 0 1mm;border-bottom:1px solid #d2dcdb;padding-bottom:1mm}
  p{margin:0;color:#4d656b;font-size:9pt;line-height:1.85}footer{margin-top:7mm;font-size:7pt;color:#788b90}
  </style></head><body><div class="template">${isAr ? "قالب سيرة ذاتية · أكمل جميع الحقول بين الأقواس قبل التقديم" : "RESUME TEMPLATE · COMPLETE ALL BRACKETED FIELDS BEFORE APPLYING"}</div><header><h1>${esc(t(profile.name))}</h1><p>${esc(t(profile.title))} / ${esc(t(profile.specialization))}</p><small>${esc(t(profile.location))}</small></header>${resumeSections.map((s, i) => `<section><h2>${esc(t(s))}</h2><p>${esc(content[i])}</p></section>`).join("")}<footer>${isAr ? "هذه نسخة قالب، وليست إثباتاً لأي مؤهل أو خبرة." : "This template is not evidence of any qualification or experience."}</footer></body></html>`;
    const page = await browser.newPage();
    await page.setContent(html);
    await page.evaluate(() => document.fonts.ready);
    const pdf = await page.pdf({
      format: "A4",
      printBackground: true,
      tagged: true,
    });
    const doc = await PDFDocument.load(pdf);
    doc.setAuthor("Perplexity Computer");
    doc.setTitle(`NAGI — ${isAr ? "Arabic" : "English"} Resume Template`);
    doc.setSubject("Editable-data biomedical engineering resume template");
    doc.setLanguage(lang);
    const path = resolve(
      root,
      `public/cv/NAGI-CV-${isAr ? "Arabic" : "English"}.pdf`,
    );
    const finalPdf = await doc.save();
    await writeFile(path, finalPdf);
    embeddedPdfs[lang] = Buffer.from(finalPdf).toString("base64");
    await writeFile(resolve(root, `qa/cv-${lang}.html`), html);
    console.log(`${path} (${doc.getPageCount()} page)`);
    await page.close();
  }
  await writeFile(
    resolve(root, "src/data/cv-pdfs.ts"),
    `// Generated by npm run cv. Do not edit by hand.\nexport const cvPdfs = ${JSON.stringify(embeddedPdfs)};\n`,
  );
} finally {
  await browser.close();
}
